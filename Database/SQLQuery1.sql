CREATE DATABASE ECOMMERCEYT
GO
USE ECOMMERCEYT;
GO
create table category(
categoryID INT PRIMARY KEY IDENTITY(1,1),categoryNAME VARCHAR(100)NOT NULL,categoryIMAGEURL VARCHAR(MAX),ISACTIVE BIT NOT NULL,CREATEDDATE DATETIME NOT NULL)

create table subcategory(
subcategoryID INT PRIMARY KEY IDENTITY(1,1),subcategoryNAME VARCHAR(100) NOT NULL,categoryId INT FOREIGN KEY REFERENCES CATEGORY (categoryID) ON DELETE CASCADE NOT NULL,ISACTIVE BIT NOT NULL ,CREATEDDATE DATETIME NOT NULL ) 
Create table product(productID INT PRIMARY KEY IDENTITY(1,1),
productNAME VARCHAR(100) NOT NULL,shortdescription VARCHAR(200)NULL,longdescription VARCHAR(max) NULL,
Additionaldescription VARCHAR(max) NULL,price decimal(18,2),Quantity int not null,Size VARCHAR(30) NULL,Color VARCHAR(50) NULL,
companyname VARCHAR(100)NULL,categoryId INT FOREIGN KEY REFERENCES CATEGORY (categoryID) ON DELETE CASCADE NOT NULL,ISACTIVE BIT NOT NULL ,subcategoryId INT NOT NULL,Sold INT NULL,CREATEDDate DATETIME NOT NULL)
CREATE TABLE PRODUCTIMAGES(
ImageID INT PRIMARY KEY IDENTITY(1,1),IMAGEURL VARCHAR(max) NULL,PRODUCTId INT FOREIGN KEY REFERENCES PRODUCT (PRODUCTId) ON DELETE CASCADE NOT NULL,
DefaultImage BIT NULL)
create table Roles(
RoleId INT PRIMARY KEY ,RoleName VARCHAR(50) NOT NULL
)
