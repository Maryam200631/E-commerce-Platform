Create TABLE Users(
userId INT PRIMARY KEY IDENTITY(1,1),Name VARCHAR(50) NULL,
username VARCHAR(50) NULL,Email VARCHAR(50) NULL,Address VARCHAR(max) NULL,postcode VARCHAR(50) NULL,Password VARCHAR(50) NULL,
ImageUrl VARCHAR(MAX)NULL,RoleId INT FOREIGN KEY REFERENCES Roles (RoleId) ON DELETE CASCADE NOT NULL,
CreatedDate DATETIME not null)

CREATE TABLE PRODUCTReview(
ReviewId INT PRIMARY KEY IDENTITY(1,1),Rating INT NOT NULL,PRODUCTId INT FOREIGN KEY REFERENCES PRODUCT (PRODUCTId) ON DELETE CASCADE NOT NULL,
userId INT FOREIGN KEY REFERENCES Users (userId) ON DELETE CASCADE NOT NULL,
CreatedDate DATETIME NOT NULL
)
CREATE TABLE Wishlist(
Wishlistid INT PRIMARY KEY IDENTITY(1,1),PRODUCTId INT FOREIGN KEY REFERENCES PRODUCT (PRODUCTId) ON DELETE CASCADE NOT NULL,
UserId INT FOREIGN KEY REFERENCES users(UserId)ON DELETE CASCADE NOT NULL)
CREATE TABLE cart(
cartId INT PRIMARY KEY IDENTITY(1,1),PRODUCTId INT FOREIGN KEY REFERENCES PRODUCT (PRODUCTId) ON DELETE CASCADE NOT NULL,
quantity INT null,UserId INT FOREIGN KEY REFERENCES users(UserId)ON DELETE CASCADE NOT NULL,CreatedDate DATETIME NOT NULL)
CREATE TABLE contact(
contactId INT PRIMARY KEY IDENTITY(1,1),name varchar(50) null,email varchar(50) null,
subject varchar(200) null,Message VARCHAR(MAX)NULL,CreatedDate DATETIME NOT NULL)
CREATE TABLE Payment(
paymentId INT PRIMARY KEY IDENTITY(1,1),name varchar(50) null,cardno varchar(50) null,
expirydate varchar(50) null,cvvno INT NULL,Address Varchar (MAX) null,paymentmode VARCHAR(50)NULL)

CREATE TABLE Orders(
ordersdateid INT PRIMARY KEY IDENTITY(1,1),
orderno VARCHAR(max)null,PRODUCTId INT FOREIGN KEY REFERENCES PRODUCT (PRODUCTId) ON DELETE CASCADE NOT NULL,
Quantity INT NULL,userId INT FOREIGN KEY REFERENCES Users (userId) ON DELETE CASCADE NOT NULL,
Status VARCHAR(50)NULL,
paymentId INT FOREIGN KEY REFERENCES Payment (paymentId) ON DELETE CASCADE NOT NULL,
OrderDate Datetime NOT NULL,ISCANCEL BIT NOT NULL DEFAULT 0
)